/**
 * Generates `BuildInfo` (version, build date, git short SHA) from `version.txt`, the single source of truth for the
 * version number. About, the update check, the installers and the MSIX manifest all read it (plan P0-4).
 */
abstract class GenerateBuildInfo : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val versionFile: RegularFileProperty

    @get:Input
    abstract val buildDate: Property<String>

    @get:Input
    abstract val commit: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val version = versionFile.get().asFile.readText().trim()
        require(Regex("""\d+\.\d+\.\d+""").matches(version)) {
            "version.txt must contain MAJOR.MINOR.PATCH (for example 1.0.0), but contains '$version'"
        }
        val dir = outputDir.get().asFile.resolve("com/titanicbhai/uiscope")
        dir.mkdirs()
        dir.resolve("BuildInfo.kt").writeText(
            """
            // Generated by the generateBuildInfo Gradle task from version.txt. Do not edit.
            package com.titanicbhai.uiscope

            object BuildInfo {
                const val VERSION: String = "$version"
                const val BUILD_DATE: String = "${buildDate.get()}"
                const val COMMIT: String = "${commit.get()}"
            }

            """.trimIndent(),
        )
    }
}

/** Short git SHA of HEAD, or "unknown" when git or the repository is not available (for example a source zip). */
fun gitShortSha(): String =
    try {
        val process = ProcessBuilder("git", "rev-parse", "--short", "HEAD")
            .directory(rootDir)
            .redirectErrorStream(true)
            .start()
        val output = process.inputStream.bufferedReader().readText().trim()
        if (process.waitFor() == 0 && Regex("[0-9a-f]{4,40}").matches(output)) output else "unknown"
    } catch (e: IOException) {
        logger.info("git not available, BuildInfo.COMMIT = unknown (${e.message})")
        "unknown"
    }

val generateBuildInfo = tasks.register<GenerateBuildInfo>("generateBuildInfo") {
    versionFile.set(rootProject.layout.projectDirectory.file("version.txt"))
    buildDate.set(LocalDate.now().toString())
    commit.set(gitShortSha())
    outputDir.set(layout.buildDirectory.dir("generated/buildinfo/kotlin"))
}

