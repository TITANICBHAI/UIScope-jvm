<#
Pins the Android platform-tools download (plan P2-4). Windows (PowerShell 5.1 or 7).

Downloads the official archives for one revision, computes their SHA-256 and rewrites
engine\src\main\kotlin\com\titanicbhai\uiscope\adb\PlatformToolsManifest.kt so the app can verify what it downloads.
Run it once now and again whenever you move to a newer platform-tools revision.

Usage:  powershell -ExecutionPolicy Bypass -File scripts\update-platform-tools.ps1 -Revision 35.0.2
        Find revisions at https://developer.android.com/tools/releases/platform-tools
        -BaseUrl is only for testing against a local server (default https://dl.google.com/android/repository)

The archive names are platform-tools_r<revision>-<windows|darwin|linux>.zip . If a download fails with 404 the name pattern or
the revision is wrong: nothing is written in that case.
#>
param(
    [Parameter(Mandatory = $true)][string]$Revision,
    [string]$BaseUrl = "https://dl.google.com/android/repository"
)
$ErrorActionPreference = "Stop"
if ($Revision -notmatch '^\d+\.\d+\.\d+$') { Write-Host "Usage: -Revision 35.0.2" -ForegroundColor Red; exit 1 }

$root = Split-Path -Parent $PSScriptRoot
$out = Join-Path $root "engine\src\main\kotlin\com\titanicbhai\uiscope\adb\PlatformToolsManifest.kt"
$work = Join-Path ([System.IO.Path]::GetTempPath()) ("uiscope-pt-" + [guid]::NewGuid().ToString("N"))
New-Item -ItemType Directory -Path $work | Out-Null
try {
    $entries = ""
    foreach ($pair in @(@("WINDOWS", "windows"), @("MACOS", "darwin"), @("LINUX", "linux"))) {
        $host_ = $pair[0]; $name = $pair[1]
        $url = "$BaseUrl/platform-tools_r$Revision-$name.zip"
        $file = Join-Path $work "$name.zip"
        Write-Host "Downloading $url"
        Invoke-WebRequest -Uri $url -OutFile $file -UseBasicParsing
        $size = (Get-Item $file).Length
        $hash = (Get-FileHash -Algorithm SHA256 -Path $file).Hash.ToLowerInvariant()
        Write-Host "  $size bytes, sha256 $hash"
        $entries += "        HostOs.$host_ to PlatformToolsEntry(`"$url`", `"$hash`", ${size}L),`n"
    }
    $kt = @"
package com.titanicbhai.uiscope.adb

import com.titanicbhai.uiscope.HostOs

/** One pinned download: an exact versioned URL (never "latest"), its SHA-256 and size. */
data class PlatformToolsEntry(val url: String, val sha256: String, val sizeBytes: Long)

data class PlatformToolsManifest(val revision: String, val entries: Map<HostOs, PlatformToolsEntry>)

/**
 * The manifest compiled into this build. **Generated by ``scripts/update-platform-tools.sh`` / ``.ps1`` for revision $Revision - do not edit by hand.**
 * It lists the exact archives the app may download and their SHA-256.
 */
object PlatformToolsManifestData {
    val MANIFEST = PlatformToolsManifest(
        revision = "$Revision",
        entries = mapOf(
$entries        ),
    )
}
"@
    [System.IO.File]::WriteAllText($out, ($kt -replace "`r`n", "`n"), (New-Object System.Text.UTF8Encoding($false)))
    Write-Host "Wrote $out"
} finally {
    Remove-Item -Recurse -Force $work -ErrorAction SilentlyContinue
}
