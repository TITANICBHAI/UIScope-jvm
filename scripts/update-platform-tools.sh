#!/usr/bin/env bash
# Pins the Android platform-tools download (plan P2-4). macOS / Linux.
#
# Downloads the official archives for one revision, computes their SHA-256 and rewrites
# engine/src/main/kotlin/com/titanicbhai/uiscope/adb/PlatformToolsManifest.kt so the app can verify what it downloads.
# Run it once now and again whenever you move to a newer platform-tools revision.
#
# Usage:  bash scripts/update-platform-tools.sh <revision>        e.g.  bash scripts/update-platform-tools.sh 35.0.2
#         Find revisions at https://developer.android.com/tools/releases/platform-tools
# Env:    PLATFORM_TOOLS_BASE_URL  (default https://dl.google.com/android/repository) — only for testing against a local server
#
# The archive file names are  platform-tools_r<revision>-<windows|darwin|linux>.zip . If a download fails with 404 the name
# pattern or the revision is wrong: nothing is written in that case.
set -euo pipefail

REV="${1:-}"
if [[ ! "$REV" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
  echo "Usage: $0 <revision>   (for example 35.0.2)" >&2
  exit 1
fi
BASE="${PLATFORM_TOOLS_BASE_URL:-https://dl.google.com/android/repository}"
OUT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/engine/src/main/kotlin/com/titanicbhai/uiscope/adb/PlatformToolsManifest.kt"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

sha256() { if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1" | cut -d' ' -f1; else shasum -a 256 "$1" | cut -d' ' -f1; fi; }

entries=""
for pair in "WINDOWS:windows" "MACOS:darwin" "LINUX:linux"; do
  host="${pair%%:*}"; name="${pair##*:}"
  url="$BASE/platform-tools_r$REV-$name.zip"
  echo "Downloading $url"
  curl -fSL --retry 2 -o "$WORK/$name.zip" "$url"
  size="$(wc -c < "$WORK/$name.zip" | tr -d ' ')"
  hash="$(sha256 "$WORK/$name.zip")"
  echo "  $size bytes, sha256 $hash"
  entries+="        HostOs.$host to PlatformToolsEntry(\"$url\", \"$hash\", ${size}L),"$'\n'
done

cat > "$OUT" <<KT
package com.titanicbhai.uiscope.adb

import com.titanicbhai.uiscope.HostOs

/** One pinned download: an exact versioned URL (never "latest"), its SHA-256 and size. */
data class PlatformToolsEntry(val url: String, val sha256: String, val sizeBytes: Long)

data class PlatformToolsManifest(val revision: String, val entries: Map<HostOs, PlatformToolsEntry>)

/**
 * The manifest compiled into this build. **Generated by \`scripts/update-platform-tools.sh\` / \`.ps1\` for revision $REV — do not edit by hand.**
 * It lists the exact archives the app may download and their SHA-256.
 */
object PlatformToolsManifestData {
    val MANIFEST = PlatformToolsManifest(
        revision = "$REV",
        entries = mapOf(
${entries}        ),
    )
}
KT
echo "Wrote $OUT"
